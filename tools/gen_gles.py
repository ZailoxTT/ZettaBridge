    # pointer is bounds-checked, and a length the registry only describes as COMPSIZE(...) is
    # resolved by hand. The sync entry points take and return a GLsync, which is a host pointer,
    # so they go through a 32-bit handle table in core/src/gl/gl_manual.cpp.
    "glClearBufferfv",
    "glClearBufferiv",
    "glClearBufferuiv",
    "glClientWaitSync",
    "glDeleteSync",
    "glDrawArraysInstanced",
    "glDrawElementsInstanced",
    "glDrawRangeElements",
    "glFenceSync",
    "glFlushMappedBufferRange",
    "glGetActiveUniformBlockiv",
    "glGetActiveUniformsiv",
    "glGetBufferPointerv",
    "glGetFragDataLocation",
    "glGetInteger64v",
    "glGetStringi",
    "glGetSynciv",
    "glGetUniformBlockIndex",
    "glGetUniformIndices",
    "glGetUniformuiv",
    "glIsSync",
    "glMapBufferRange",
    "glTexImage3D",
    "glTexSubImage3D",
    "glTransformFeedbackVaryings",
